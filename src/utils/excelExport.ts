import { Technician, InventoryItem, UserProfile } from '../types';

export interface ExportExcelOptions {
  technicians: Technician[];
  inventory: InventoryItem[];
  selectedTechId?: string | 'ALL';
  currentUser: UserProfile;
}

/**
 * Generates an Excel-compatible CSV with UTF-8 BOM, Slot Tracking, Pairing Status,
 * Total On-Hand Stocks, and Warehouse Item Utilization for Technician Accounts.
 */
export function generateTechnicianExcelData({
  technicians,
  inventory,
  selectedTechId = 'ALL',
  currentUser,
}: ExportExcelOptions) {
  const targetTechs =
    selectedTechId === 'ALL'
      ? technicians
      : technicians.filter((t) => t.id === selectedTechId);

  const now = new Date();
  const timestamp = now.toISOString().replace('T', ' ').substring(0, 19);

  // Helper to escape CSV fields safely
  const escapeCsv = (val: string | number | boolean | null | undefined): string => {
    if (val === null || val === undefined) return '""';
    const str = String(val).replace(/"/g, '""');
    return `"${str}"`;
  };

  const lines: string[] = [];

  // 1. Report Title & Metadata Header Block
  lines.push(`"FIBERX INVENTORY MANAGEMENT SYSTEM - TECHNICIAN DISPATCH & ON-HAND CUSTODY MANIFEST"`);
  lines.push(`"Export Timestamp:",${escapeCsv(timestamp)},"Generated By:",${escapeCsv(`${currentUser.name} (${currentUser.role})`)},"Badge ID:",${escapeCsv(currentUser.badgeId)}`);
  lines.push(`"Scope:",${escapeCsv(selectedTechId === 'ALL' ? 'All Fleet Technician Accounts' : targetTechs[0]?.name || 'Single Technician')},"Total Technicians:",${escapeCsv(targetTechs.length)}`);
  lines.push('');

  // 2. Technician Summary Block (Total On-Hand Stocks Assigned)
  lines.push(`"=== TECHNICIAN FLEET SUMMARY & ON-HAND INVENTORY CUSTODY ==="`);
  lines.push(
    [
      'Technician ID',
      'Technician Name',
      'Employee ID',
      'Contact Phone',
      'Assigned Van',
      'Service Area',
      'Flag Status',
      'Flag Reason',
      'Total On-Hand Stock (Units)',
      'Unique Products Handled',
      'Warehouse Items Utilized (Used)',
      'Connected / Closed Accounts',
      'Supervisor Contact',
      'Fulfillment Hub Address',
    ]
      .map(escapeCsv)
      .join(',')
  );

  targetTechs.forEach((tech) => {
    const techItems = inventory.filter(
      (item) =>
        !item.archived &&
        (item.assignedTechnicianId === tech.id ||
          item.submittedByTechnicianId === tech.id ||
          item.closedByTechnicianId === tech.id)
    );

    const onHandItems = techItems.filter(
      (i) =>
        i.assignedTechnicianId === tech.id &&
        (i.lifecycleStatus === 'ASSIGNED_RESERVED' || i.status === 'ASSIGNED') &&
        (i.verificationStatus === 'UNLINKED_READY' || !i.customerAccountNumber)
    );

    const totalOnHandUnits = onHandItems.reduce((sum, i) => sum + (i.quantity || 1), 0);
    const uniqueProductsCount = new Set(onHandItems.map((i) => i.sku || i.name)).size;

    const utilizedCount = techItems.filter(
      (i) =>
        i.isUtilized ||
        (i.utilizedQuantity && i.utilizedQuantity > 0) ||
        i.verificationStatus === 'VERIFIED_CONNECTED' ||
        i.lifecycleStatus === 'INSTALLED_DEPLOYED'
    ).length;

    const connectedCount = techItems.filter(
      (i) =>
        i.verificationStatus === 'VERIFIED_CONNECTED' ||
        i.status === 'INSTALLED_VERIFIED' ||
        i.status === 'INSTALLED_CLOSED'
    ).length;

    lines.push(
      [
        tech.id,
        tech.name,
        tech.employeeId,
        tech.phone,
        tech.assignedVan,
        tech.area,
        tech.isFlagged ? 'FLAGGED / OVERRIDE REQUIRED' : 'CLEAR / ACTIVE',
        tech.flagReason || 'N/A',
        totalOnHandUnits,
        uniqueProductsCount,
        utilizedCount,
        connectedCount,
        tech.contactPerson || 'N/A',
        tech.hubAddress || 'Main Logistics Warehouse',
      ]
        .map(escapeCsv)
        .join(',')
    );
  });

  lines.push('');
  lines.push(`"=== DETAILED EQUIPMENT ROSTER WITH SLOT TRACKING & PRODUCT PAIRING ==="`);

  // 3. Detailed Equipment Columns with Slot Tracking & Product Pairing
  const equipmentHeaders = [
    'Technician Account',
    'Employee ID',
    'Slot # (Rack/Van Slot)',
    'Pairing Status',
    'Paired Companion Product / Serial',
    'Product / Equipment Name',
    'Serial Number / Barcode',
    'SKU',
    'Category',
    'Brand & Model',
    'Assigned Qty',
    'Unit',
    'Warehouse Utilized (Used Qty)',
    'On-Hand Remaining Qty',
    'Current Lifecycle Status',
    'Verification Status',
    'Storage Bin / Van Location',
    'Assigned At',
    'Assigned By (Dispatcher)',
    'Subscriber Account #',
    'Subscriber Name',
    'Service Address',
    'Optical Rx Power',
    'Dispatch Hub Address',
    'Dispatcher Contact',
  ];

  lines.push(equipmentHeaders.map(escapeCsv).join(','));

  targetTechs.forEach((tech) => {
    const techItems = inventory.filter(
      (item) =>
        !item.archived &&
        (item.assignedTechnicianId === tech.id ||
          item.submittedByTechnicianId === tech.id ||
          item.closedByTechnicianId === tech.id)
    );

    techItems.forEach((item, index) => {
      // Slot tracking: use assigned slotNumber or deterministic slot based on position
      const slotNum = item.slotNumber || `SLOT-${String((index % 24) + 1).padStart(2, '0')}`;

      // Pairing status logic: check if paired with companion equipment or customer account
      const isPaired =
        item.pairingStatus === 'PAIRED' ||
        Boolean(item.pairedItemSerial) ||
        Boolean(item.customerAccountNumber) ||
        item.category === 'MODEM_ONT';

      const pairingStatus = isPaired ? 'PAIRED' : 'UNPAIRED';

      // Paired reference
      const pairedRef =
        item.pairedItemName && item.pairedItemSerial
          ? `${item.pairedItemName} [${item.pairedItemSerial}]`
          : item.customerAccountNumber
          ? `Subscriber: ${item.customerAccountNumber} (${item.customerName || 'Bound'})`
          : item.category === 'MODEM_ONT'
          ? 'Paired with Drop Cable & Splitter Port'
          : item.category === 'FIBER_CABLE'
          ? 'Paired with Customer Premises ONT Gateway'
          : 'Stand-alone stock';

      // Utilization check:
      const utilizedQty =
        item.utilizedQuantity !== undefined
          ? item.utilizedQuantity
          : item.verificationStatus === 'VERIFIED_CONNECTED' ||
            item.lifecycleStatus === 'INSTALLED_DEPLOYED'
          ? item.quantity
          : 0;

      const remainingOnHand = Math.max(0, item.quantity - utilizedQty);

      lines.push(
        [
          tech.name,
          tech.employeeId,
          slotNum,
          pairingStatus,
          pairedRef,
          item.name,
          item.serialNumber || 'N/A',
          item.sku,
          item.category,
          `${item.brand || ''} ${item.modelName || ''}`.trim(),
          item.quantity,
          item.unit,
          utilizedQty,
          remainingOnHand,
          item.lifecycleStatus,
          item.verificationStatus,
          item.storageBin || tech.assignedVan,
          item.assignedAt || item.receivedDate || '—',
          item.assignedByUserName || `${currentUser.name} (${currentUser.role})`,
          item.customerAccountNumber || 'Unlinked',
          item.customerName || 'N/A',
          item.customerAddress || tech.area,
          item.opticalRx || 'N/A',
          item.dispatchHubAddress || tech.hubAddress || 'Main Logistics Warehouse',
          tech.contactPerson || 'N/A',
        ]
          .map(escapeCsv)
          .join(',')
      );
    });
  });

  // Prepend UTF-8 BOM so Excel opens it with full accents and special symbols
  const csvContent = '\uFEFF' + lines.join('\r\n');
  return csvContent;
}

/**
 * Triggers automatic browser download of the Excel-formatted CSV.
 */
export function downloadTechnicianExcelFile(options: ExportExcelOptions) {
  const csvData = generateTechnicianExcelData(options);
  const blob = new Blob([csvData], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');

  const filenamePrefix =
    options.selectedTechId && options.selectedTechId !== 'ALL'
      ? `fiberx_tech_${options.selectedTechId}_inventory_slots`
      : 'fiberx_all_technicians_inventory_slots';

  const dateStr = new Date().toISOString().split('T')[0];
  link.href = url;
  link.setAttribute('download', `${filenamePrefix}_${dateStr}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
